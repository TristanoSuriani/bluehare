"""The distributions (distributions/<name>.txt: the engines in display order, one a line, at most 16; and optionally a
`TRACKS 4` or `TRACKS 8` line, the build's track count, 4 without one; and a `PALETTE <name>` line, the palette a
device starts with, tools/gen_ui_palettes.py's, GREY without one) -> a header
each, OUT_DIR/dist_<name>.h, that firmware/src/core.h includes for the one being built (FELUCCA_DIST=<name>):
  FELUCCA_DIST_TAG         "" for one named "default", else " <NAME>" (the version string, the package name)
  FELUCCA_DIST_PRIMARY     1 for distributions/BUILD's (what a plain build builds: the host tests' full set), else 0
  FELUCCA_ENG_<NAME>       1 for the engines in it, 0 for every other engine of firmware/src/engine_ids.h
  FELUCCA_DIST_ENGINES(X)  X(NAME) for each, in order: the build's engine indices
  FELUCCA_TRACKS           its track count (4 or 8: firmware/src/core.h NTRK)
  FELUCCA_DIST_PALETTE     UI_PAL_<name> (or UI_GREY_INDEX): the palette until the settings hold one
  ENGI_<NAME> ENG_ABSENT   for every engine it leaves out
  gen_dist.py SRC_ROOT OUT_DIR"""
import re
import sys
from pathlib import Path

MAX = 16


def registry(root):
    text = (root / "firmware" / "src" / "engine_ids.h").read_text()
    return [m.group(1) for m in re.finditer(r"^ENGINE\((\w+),\s*\d+,\s*\w+\)", text, re.M)]


def read(path, known):
    names, tracks, palette = [], 4, None
    for n, line in enumerate(path.read_text().splitlines(), 1):
        line = line.split("#", 1)[0].strip().upper()
        if not line:
            continue
        if line.startswith("TRACKS"):
            words = line.split()
            if len(words) != 2 or words[1] not in ("4", "8"):
                raise SystemExit(f"{path}:{n}: TRACKS 4 or TRACKS 8")
            tracks = int(words[1])
            continue
        if line.startswith("PALETTE"):               # (Fel-Tracker) the palette a device starts with
            words = line.split()
            if len(words) != 2 or not re.fullmatch(r"[A-Z][A-Z0-9-]*", words[1]):
                raise SystemExit(f"{path}:{n}: PALETTE <name> (tools/gen_ui_palettes.py)")
            palette = words[1].replace("-", "_")
            continue
        if line not in known:
            raise SystemExit(f"{path}:{n}: unknown engine {line} (firmware/src/engine_ids.h: {' '.join(known)})")
        if line in names:
            raise SystemExit(f"{path}:{n}: {line} twice")
        names.append(line)
    if not names or len(names) > MAX:
        raise SystemExit(f"{path}: {len(names)} engines (1 .. {MAX})")
    return names, tracks, palette


def primary(root):
    lines = [l.strip() for l in (root / "distributions" / "BUILD").read_text().splitlines()]
    return next(l for l in lines if l and not l.startswith("#")).lower()


def main(root, out):
    root, out = Path(root), Path(out)
    known = registry(root)
    first = primary(root)
    out.mkdir(parents=True, exist_ok=True)
    for path in sorted((root / "distributions").glob("*.txt")):
        name = path.stem.lower()
        if not re.fullmatch(r"[a-z][a-z0-9_]*", name):
            raise SystemExit(f"{path}: a distribution's name is lower case letters, digits, _")
        names, tracks, palette = read(path, known)
        tag = "" if name == "default" else " " + name.upper()
        lines = [f"/* generated by tools/gen_dist.py from distributions/{path.name}: do not edit */",
                 f'#define FELUCCA_DIST_TAG "{tag}"', f"#define FELUCCA_DIST_PRIMARY {int(name == first)}"]
        lines += [f"#define FELUCCA_ENG_{k} {int(k in names)}" for k in known]
        lines.append("#define FELUCCA_DIST_ENGINES(X) " + " ".join(f"X({k})" for k in names))
        lines.append(f"#define FELUCCA_TRACKS {tracks}")
        lines.append(f"#define FELUCCA_DIST_PALETTE {'UI_PAL_' + palette if palette else 'UI_GREY_INDEX'}")
        lines += [f"#define ENGI_{k} ENG_ABSENT" for k in known if k not in names]
        (out / f"dist_{name}.h").write_text("\n".join(lines) + "\n")
        print(f"distribution {name}: {len(names)} engines, {tracks} tracks")


if __name__ == "__main__":
    main(*sys.argv[1:3])
