"""(2026-10-18) Niglio, Blue Hare's mascot (assets/niglio.png, the user's), for the power-on splash (ui_draw.c
draw_splash): scaled to NG_W x NG_H, sixteen colours (the darkest the screen's ground: index 0, drawn in the palette's
BG), four bits a pixel, two to a byte, rows back to back.
  gen_niglio.py OUT.h"""
import sys
from pathlib import Path

from PIL import Image

W = H = 152
SRC = Path(__file__).resolve().parents[1] / "assets" / "niglio.png"


def rgb565(r, g, b):
    return (r >> 3) << 11 | (g >> 2) << 5 | b >> 3


def main(out):
    im = Image.open(SRC).convert("RGB")
    bbox = (int(im.width * .1), int(im.height * .06), int(im.width * .9), int(im.height * .94))   # (the figure, its glow)
    im = im.crop(bbox).resize((W, H), Image.LANCZOS)
    q = im.quantize(colors=16, method=Image.Quantize.MEDIANCUT)
    pal = q.getpalette()[:48]
    cols = [tuple(pal[i * 3:i * 3 + 3]) for i in range(16)]
    dark = min(range(16), key=lambda i: sum(cols[i]))
    order = [dark] + [i for i in range(16) if i != dark]          # the ground first
    remap = {o: n for n, o in enumerate(order)}
    ground = {o for o in range(16) if sum(cols[o]) < 75}          # the background's near-blacks: all the ground
    px = [0 if p in ground else remap[p] for p in q.tobytes()]
    data = bytes((px[i] << 4) | px[i + 1] for i in range(0, len(px), 2))
    lines = ["/* generated by tools/gen_niglio.py from assets/niglio.png: Niglio, Blue Hare's mascot */", "#pragma once",
             f"#define NG_W {W}", f"#define NG_H {H}",
             "static const uint16_t NG_PAL[16] = {" + ", ".join(f"0x{rgb565(*cols[o]):04X}" for o in order) + "};",
             f"static const uint8_t NG_PX[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"niglio: {W} x {H}, 16 colours, {len(data)} B -> {out}")


if __name__ == "__main__":
    main(sys.argv[1])
